const themeInitScript = `
(function () {
  try {
  var mode = localStorage.getItem("epsilone-theme-mode");

    var dark = false;

    if (mode === "dark") {
      dark = true;
    } else if (mode === "light") {
      dark = false;
    } else if (mode === "iran-time") {
      var parts = new Intl.DateTimeFormat("en-US", {
        timeZone: "Asia/Tehran",
        hour: "2-digit",
        hourCycle: "h23"
      }).formatToParts(new Date());

      var hour = Number(
        parts.find(function (part) {
          return part.type === "hour";
        })?.value ?? "12"
      );

      // Light: 07:00–18:59 Iran time
      // Dark: 19:00–06:59 Iran time
      dark = hour < 7 || hour >= 19;
    } else {
      dark = window.matchMedia(
        "(prefers-color-scheme: dark)"
      ).matches;
    }

    document.documentElement.classList.toggle("dark", dark);

    document.documentElement.style.colorScheme = dark
      ? "dark"
      : "light";
  } catch (error) {
    // Theme initialization must not prevent the app from loading.
  }
})();
`;

